"""Day 1 复习：六种基础类型，每种 3 个小例子。"""

# ============================================================
# 1. 变量
# ============================================================
# 变量是数据的“标签”，赋值即创建。
# 例 1
name = "小明"
print("变量例1:", name)

# 例 2：变量可以重新赋值，类型也可以改变
count = 10
count = "十"
print("变量例2:", count)

# 例 3：多个变量同时赋值
x, y, z = 1, 2, 3
print("变量例3:", x, y, z)


# ============================================================
# 2. 字符串（str）
# ============================================================
# 例 1：基本字符串与拼接
greeting = "Hello" + " " + "World"
print("字符串例1:", greeting)

# 例 2：f-string 格式化（Python 3.6+）
username = "Alice"
message = f"欢迎你，{username}！"
print("字符串例2:", message)

# 例 3：常用方法：upper()、strip()、split()
raw = "  python is fun  "
print("字符串例3:", raw.strip().upper().split())


# ============================================================
# 3. 数字（int / float）
# ============================================================
# 例 1：整数运算
a = 10
b = 3
print("数字例1:", a + b, a - b, a * b)

# 例 2：浮点数与除法
price = 19.9
quantity = 3
print("数字例2:", price * quantity)

# 例 3：整除、取余、幂运算
print("数字例3:", 10 // 3, 10 % 3, 2 ** 4)


# ============================================================
# 4. 布尔值（bool）
# ============================================================
# 只有 True 和 False 两个值。
# 例 1：直接赋值
is_student = True
print("布尔例1:", is_student)

# 例 2：比较运算返回布尔值
age = 20
print("布尔例2:", age >= 18, age < 18)

# 例 3：布尔值与逻辑运算符
has_ticket = True
has_id = False
print("布尔例3:", has_ticket and has_id, has_ticket or has_id)


# ============================================================
# 5. 列表（list）
# ============================================================
# 有序、可变的序列，用 [] 表示。
# 例 1：创建与索引
fruits = ["apple", "banana", "cherry"]
print("列表例1:", fruits[0], fruits[-1])

# 例 2：添加与删除
fruits.append("orange")
fruits.remove("banana")
print("列表例2:", fruits)

# 例 3：切片与长度
numbers = [10, 20, 30, 40, 50]
print("列表例3:", numbers[1:4], len(numbers))


# ============================================================
# 6. 字典（dict）
# ============================================================
# 键值对集合，用 {} 表示，键必须唯一。
# 例 1：创建与访问
person = {"name": "小明", "age": 20, "city": "上海"}
print("字典例1:", person["name"], person["city"])

# 例 2：添加与修改
person["age"] = 21
person["email"] = "xiaoming@example.com"
print("字典例2:", person)

# 例 3：安全访问与遍历
print("字典例3:", person.get("phone", "未填写"))
for key, value in person.items():
    print(f"  {key}: {value}")